const CATALOGS: Record<AppLocale, Record<MessageKey, string>> = { en: EN, de: DE, ar: AR };
const RTL_LOCALES = new Set<AppLocale>(['ar']);
const [activeLocale, setActiveLocale] = createSignal<AppLocale>('en');

export { activeLocale };

export const LOCALE_OPTIONS: ReadonlyArray<{
  value: LocalePreference;
  label: MessageKey;
}> = [
  { value: 'system', label: 'locale.system' },
  { value: 'en', label: 'locale.english' },
  { value: 'de', label: 'locale.german' },
  { value: 'ar', label: 'locale.arabic' },
];

function languageCode(value: string): string {
  return value.trim().toLocaleLowerCase().split(/[-_]/, 1)[0] ?? '';
}

export function resolveLocale(
  preference: LocalePreference,
  languages: readonly string[] = typeof navigator === 'undefined'
    ? []
    : navigator.languages,
): AppLocale {
  if (preference !== 'system') return preference;
  for (const language of languages) {
    const code = languageCode(language);
    if (SUPPORTED_LOCALES.includes(code as AppLocale)) return code as AppLocale;
  }
  return 'en';
}

export function localeDirection(locale = activeLocale()): TextDirection {
  return RTL_LOCALES.has(locale) ? 'rtl' : 'ltr';
}

export function applyLocalePreference(preference: LocalePreference): AppLocale {
  const locale = resolveLocale(preference);
  setActiveLocale(locale);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    document.documentElement.dir = localeDirection(locale);
  }
  return locale;
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  const template = CATALOGS[activeLocale()][key] ?? EN[key];
  return template.replace(/\{([a-zA-Z][\w-]*)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}

export function formatDate(value: Date | number, options: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(activeLocale(), options).format(value);
}

export function formatNumber(value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(activeLocale(), options).format(value);
}

export function formatRelative(
  value: number,
  unit: Intl.RelativeTimeFormatUnit,
  numeric: 'always' | 'auto' = 'always',
): string {
  return new Intl.RelativeTimeFormat(activeLocale(), { numeric }).format(value, unit);
}
